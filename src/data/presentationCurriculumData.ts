export interface GsebSubject {
  id: string;
  name: string; // Gujarati name
  icon: string;
  standards: number[]; // [9, 10] or [11, 12]
  popularTopics: Array<{
    topic: string;
    chapter?: string;
    standard: number;
    description: string;
    hasBlackboard: boolean;
  }>;
}

export interface DetailedExampleItem {
  title: string;
  context: string;
  scientificReason: string;
  reasonLabel?: string;
  speechQuote?: string;
}

export interface PracticalActivityData {
  hasActivity: boolean;
  title: string;
  textbookRef?: string;
  materials?: string[];
  procedure?: string[];
  observation?: string;
  conclusion?: string;
  stageDemoTip?: string;
  description: string;
}

export interface PresentationScriptData {
  title: string;
  standard: string;
  subject: string;
  duration: string;
  environment: string; // 'પ્રાર્થના સંમેલન / સભા' | 'વર્ગખંડ પ્રસ્તુતિ'
  studentName?: string;

  // ૫ મિનિટ અસ્ખલિત બોલી શકાય તેવું સંપૂર્ણ સ્પીચ લખાણ (સરળ ગુજરાતીમાં):
  openingSpeech: string; // ૧. પ્રારંભિક સંબોધન & શરૂઆત (સભા અથવા ક્લાસરૂમ મુજબ)
  topicIntroduction: string; // ૨. વિષય પરિચય અને સાદી વ્યાખ્યા
  detailedExplanation: string; // ૩. વિષયની વિસ્તૃત સમજૂતી (૫ મિનિટ રજૂઆત માટેનું સમૃદ્ધ લખાણ)
  realLifeExample: string; // ૪. રોજિંદા જીવન સાથે જોડાયેલું સચોટ ઉદાહરણ
  detailedExamples?: DetailedExampleItem[]; // ઊંડાણપૂર્વક સમજાવેલા રોજિંદા ઉદાહરણો
  practicalActivity?: PracticalActivityData; // GSEB પાઠ્યપુસ્તક આધારિત સચોટ પ્રવૃત્તિ
  audienceQuestion?: {
    question: string;
    expectedAnswer: string;
  };
  closingSpeech: string; // ૫. પ્રેરણાદાયી સમાપન અને આભારવિધિ
  keyPointsToRemember: string[]; // યાદ રાખવાના ૪-૫ મુખ્ય મુદ્દા (Quick Summary)

  // Backwards compatibility fields
  hook?: string;
  introduction?: string;
  conclusion?: string;
}

